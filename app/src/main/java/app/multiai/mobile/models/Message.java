    /**
     * Уже ли этот текст лежит в одном из CONTENT-сегментов workflow.
     * Защита от повторной вставки текста, который был перенесён в drawer:
     * иначе он дублируется под финальным ответом.
     */
    public boolean workflowContainsContentText(String text) {
        if (workflowSegments == null || text == null) return false;
        String needle = text.trim();
        if (needle.isEmpty()) return false;
        for (WorkflowSegment segment : workflowSegments) {
            if (segment == null || segment.getType() != WorkflowSegment.TYPE_CONTENT) continue;
            String stored = segment.getContentText();
            if (stored == null) continue;
            if (stored.trim().equals(needle)) return true;
        }
        return false;
    }

    public boolean moveStandaloneContentToWorkflow() {
        String value = getContentSafe();
        if (!isStandaloneContentVisible() || value.trim().isEmpty()) return false;
        appendWorkflowContent(value);
        content = "";
        standaloneContentVisible = false;
        return true;
    }

    /**
     * Compatibility cleanup for restored chats. Structured workflow timelines
     * are already chronological and must never be rearranged during app
     * startup — only genuinely inconsistent states are repaired.
     */
    public boolean normalizeWorkflowContentState() {
        if (workflowSegments == null || workflowSegments.isEmpty()) return false;

        String value = getContentSafe().trim();

        // Repair a hidden final answer. moveStandaloneContentToWorkflow() is
        // the only producer of standaloneContentVisible=false and it always
        // clears content, so "hidden + non-empty content" cannot be a state
        // the UI ever meant to render: the bubble simply vanished after the
        // chat came back from storage. Restore it and drop the drawer copy so
        // the answer is not printed twice.
        if (!isStandaloneContentVisible()) {
            if (value.isEmpty()) return false;
            removeDuplicateContentSegments(value);
            standaloneContentVisible = true;
            return true;
        }

        // A thinking/tool timeline owns its original order. The former repair
        // removed content segments and forcibly moved the standalone bubble,
        // which made a completed workflow jump beside the final response after
        // Gson restored the chat.
        if (hasStructuredWorkflowSegment()) return false;

        if (value.isEmpty()) return false;
        return removeDuplicateContentSegments(value);
    }

    /** Есть ли в timeline сегменты, задающие его хронологию (thinking / tools). */
    private boolean hasStructuredWorkflowSegment() {
        if (workflowSegments == null) return false;
        for (WorkflowSegment segment : workflowSegments) {
            if (segment == null) continue;
            if (segment.getType() == WorkflowSegment.TYPE_THINKING
                    || segment.getType() == WorkflowSegment.TYPE_TOOL_CALLS) {
                return true;
            }
        }
        return false;
    }

    /** Убирает CONTENT-сегменты, дублирующие видимый текст сообщения. */
    private boolean removeDuplicateContentSegments(String trimmedContent) {
        if (workflowSegments == null || trimmedContent == null || trimmedContent.isEmpty()) {
            return false;
        }
        boolean changed = false;
        for (int i = workflowSegments.size() - 1; i >= 0; i--) {
            WorkflowSegment segment = workflowSegments.get(i);
            if (segment != null && segment.getType() == WorkflowSegment.TYPE_CONTENT
                    && trimmedContent.equals(segment.getContentText() == null
                    ? "" : segment.getContentText().trim())) {
                workflowSegments.remove(i);
                changed = true;
            }
        }
        return changed;
    }

    /** Есть ли в workflow хотя бы один thinking-сегмент с реальным контентом. */
    public boolean hasWorkflowThinking() {
        if (workflowSegments == null) return false;
        for (WorkflowSegment seg : workflowSegments) {
            if (seg.getType() == WorkflowSegment.TYPE_THINKING) {
                String t = seg.getThinkingText();
                if (t != null && !t.trim().isEmpty()) return true;
            }
        }
        return false;
    }

    /** Есть ли в workflow хотя бы один tool-calls-сегмент с вызовами. */
    public boolean hasWorkflowToolCalls() {
        if (workflowSegments == null) return false;
        for (WorkflowSegment seg : workflowSegments) {
            if (seg.getType() == WorkflowSegment.TYPE_TOOL_CALLS
                    && seg.getToolCalls() != null && !seg.getToolCalls().isEmpty()) {
                return true;
            }
        }
        return false;
    }

    /**
     * Хэш presentation-состояния для адаптера: меняется, когда меняется то,
     * что видно пользователю (thinking-текст, статусы/результаты/expanded
     * tool calls, expanded-состояния, рабочее состояние, сегменты).
     * Используется для дедупликации перерисовок и не пишет I/O.
     */
    public long presentationFingerprint() {
        long hash = 1125899906842597L;
        hash = 31L * hash + type;
        hash = 31L * hash + (workflowStopped ? 1 : 0);
        hash = 31L * hash + (workingState ? 1 : 0);
        hash = 31L * hash + (toolWorkflowSummary ? 1 : 0);
        hash = 31L * hash + (workflowCollapsedManually ? 1 : 0);
        hash = 31L * hash + (toolWorkflowExpanded ? 1 : 0);
        String visible = content != null
                ? content.replaceAll("(?s)<(?:think|thinking|reasoning)>.*?(?:</(?:think|thinking|reasoning)>|$)", "")
                : "";
        String trimmedVisible = visible.trim();
        hash = 31L * hash + trimmedVisible.length();
        hash = 31L * hash + trimmedVisible.hashCode();
        String think = thinkingContent != null
                ? thinkingContent.replaceAll("(?i)</?(?:think|thinking|reasoning)>", "").trim()
                : "";
        hash = 31L * hash + think.length();
        hash = 31L * hash + think.hashCode();
        if (toolCalls != null) {
            hash = 31L * hash + toolCalls.size();
            for (ToolCall call : toolCalls) {
                hash = hash * 1000003L;
                if (call == null) continue;
                hash += java.util.Objects.hashCode(call.getName());
                hash = 31L * hash + java.util.Objects.hashCode(call.getStatus());
                hash = 31L * hash + (call.isExpanded() ? 1 : 0);
                hash = 31L * hash + (call.isExploreExpanded() ? 1 : 0);
                org.json.JSONObject result = call.getResult();
                hash = 31L * hash + (result == null ? 0 : result.toString().hashCode());
            }
        }
        if (workflowSegments != null) {
            for (WorkflowSegment seg : workflowSegments) {
                hash = hash * 1000003L;
                if (seg == null) continue;
                hash += seg.getType();
                if (seg.getType() == WorkflowSegment.TYPE_THINKING) {
                    String t = seg.getThinkingText() != null ? seg.getThinkingText().trim() : "";
                    hash = 31L * hash + t.length();
                    hash = 31L * hash + t.hashCode();
                } else if (seg.getType() == WorkflowSegment.TYPE_CONTENT) {
                    String c = seg.getContentText() != null ? seg.getContentText() : "";
                    hash = 31L * hash + c.length();
                    hash = 31L * hash + c.hashCode();
                } else {
                    List<ToolCall> calls = seg.getToolCalls();
                    hash = 31L * hash + (calls == null ? 0 : calls.size());
                    if (calls != null) {
                        for (ToolCall call : calls) {
                            hash = hash * 1000003L;
                            if (call == null) continue;
                            hash += java.util.Objects.hashCode(call.getName());
                            hash = 31L * hash + java.util.Objects.hashCode(call.getStatus());
                            hash = 31L * hash + (call.isExpanded() ? 1 : 0);
                            hash = 31L * hash + (call.isExploreExpanded() ? 1 : 0);
                            org.json.JSONObject result = call.getResult();
                            hash = 31L * hash + (result == null ? 0 : result.toString().hashCode());
                        }
                    }
                }
            }
        }
        return hash;
    }

