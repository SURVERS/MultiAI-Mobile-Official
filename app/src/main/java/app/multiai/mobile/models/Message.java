    public void addAlternateContent(String nextContent, String nextThinkingContent,
                                    List<WorkflowSegment> nextWorkflowSegments) {
        String current = getContentSafe();
        String currentThinking = effectiveThinking(thinkingContent, workflowSegments);
        String nextThinking = effectiveThinking(nextThinkingContent, nextWorkflowSegments);
        if (alternateContents == null) alternateContents = new ArrayList<>();
        if (alternateThinkingContents == null) alternateThinkingContents = new ArrayList<>();
        if (alternateWorkflowSegments == null) alternateWorkflowSegments = new ArrayList<>();
        if (alternateContents.isEmpty()) {
            alternateContents.add(current);
            alternateThinkingContents.add(currentThinking);
            alternateWorkflowSegments.add(workflowSegments);
        }
        while (alternateThinkingContents.size() < alternateContents.size()) {
            alternateThinkingContents.add("");
        }
        while (alternateWorkflowSegments.size() < alternateContents.size()) {
            alternateWorkflowSegments.add(null);
        }
        alternateContents.add(nextContent != null ? nextContent : "");
        alternateThinkingContents.add(nextThinking);
        alternateWorkflowSegments.add(nextWorkflowSegments);
        selectedVariant = alternateContents.size() - 1;
        content = alternateContents.get(selectedVariant);
        thinkingContent = alternateThinkingContents.get(selectedVariant);
        workflowSegments = alternateWorkflowSegments.get(selectedVariant);
    }

    private static String effectiveThinking(String thinking, List<WorkflowSegment> segments) {
        if (thinking != null && !thinking.trim().isEmpty()) return thinking;
        if (segments == null) return "";
        StringBuilder combined = new StringBuilder();
        for (WorkflowSegment segment : segments) {
            if (segment == null || segment.getType() != WorkflowSegment.TYPE_THINKING) continue;
            String text = segment.getVisibleThinkingText();
            if (text.isEmpty()) continue;
            if (combined.length() > 0) combined.append("\n\n");
            combined.append(text);
        }
        return combined.toString();
    }

    public void selectVariant(int index) {
        if (alternateContents == null || alternateContents.isEmpty()) return;
        if (index < 0 || index >= alternateContents.size()) return;
        selectedVariant = index;
        content = alternateContents.get(index);
        thinkingContent = alternateThinkingContents != null && index < alternateThinkingContents.size()
                ? alternateThinkingContents.get(index) : "";
        workflowSegments = alternateWorkflowSegments != null && index < alternateWorkflowSegments.size()
                ? alternateWorkflowSegments.get(index) : null;
    }
    
