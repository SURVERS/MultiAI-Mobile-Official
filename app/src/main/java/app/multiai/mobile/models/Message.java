    /**
     * Единая политика раскрытия workflow-карточки.
     *
     * Ключевая логика ремонта:
     * 1. Workflow автоматически открыт (expanded=true), пока идёт работа
     *    (workingState) или ход завершился с summary — ЕСЛИ пользователь
     *    явно не свернул карточку вручную (workflowCollapsedManually=false).
     * 2. Ручное состояние переживает любые ререндеры: пока флаг
     *    workflowCollapsedManually=true, авто-раскрытие отключено, а само
     *    expanded берётся из последнего ручного выбора пользователя.
     * 3. Старые чаты (после Gson-десериализации) имеют все transient-флаги
     *    false; для них поведение как раньше: авто-раскрытие при первом
     *    показе, свёрнуто — после ручного сворачивания.
     */
    public boolean computeWorkflowExpanded(boolean summaryVisible) {
        boolean hasWorkflow = workingState || summaryVisible || toolWorkflowSummary;
        if (!hasWorkflow) return true; // без карточки — старое поведение "всё видно"
        if (workflowCollapsedManually) return toolWorkflowExpanded; // ручной выбор
        if (workingState) {
            // Во время работы — авто-открыто, но не силой открываем то, что
            // пользователь свернул в этом же ходе (флаг выше).
            toolWorkflowExpanded = true;
            workflowAutoOpened = true;
            return true;
        }
        if (summaryVisible || toolWorkflowSummary) {
            toolWorkflowExpanded = true;
            workflowAutoOpened = true;
            return true;
        }
        return toolWorkflowExpanded;
    }

